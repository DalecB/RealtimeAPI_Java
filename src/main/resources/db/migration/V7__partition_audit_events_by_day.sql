-- audit_events를 event_time 기준 일 단위(UTC) 범위 파티션 테이블로 바꾼다. 30일 지난 파티션은
-- AuditEventPartitionJob이 DROP한다(DELETE와 달리 bloat·VACUUM 부담이 없다).
-- PG는 기존 테이블을 파티션 테이블로 ALTER할 수 없으므로 새로 만들고, 행을 옮긴 뒤 이름을 바꾼다.
-- Flyway가 이 파일을 한 트랜잭션으로 실행하므로 중간에 실패하면 전부 롤백된다.

-- 1. 새 파티션 테이블. 제약·인덱스는 이름 충돌을 피하려고 기존 테이블을 지운 뒤(4번) 붙인다.
CREATE TABLE audit_events_partitioned (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    leaderboard_id  UUID        NOT NULL,
    event_id        VARCHAR(40) NOT NULL,   -- Redis 스트림 엔트리 ID "<ms>-<seq>"
    event_time      TIMESTAMPTZ NOT NULL,   -- event_id의 ms 부분(Redis 서버 시계). 파티션 키이자 버킷 집계 기준.
    event_type      VARCHAR(16) NOT NULL
        CONSTRAINT audit_events_event_type_check CHECK (event_type IN ('new', 'conflict')),
    user_id         BIGINT      NOT NULL,
    delta           BIGINT      NOT NULL,   -- conflict일 때는 거부된(들어온) 값
    api_key_id      BIGINT      NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
) PARTITION BY RANGE (event_time);

-- 2. 기존 행이 걸친 날짜마다 파티션을 만든다. 빈 DB면 아무것도 만들지 않는다.
--    경계는 UTC 자정으로 고정한다. 세션 TimeZone에 따라 경계가 밀리지 않게 AT TIME ZONE 'UTC'로 계산한다.
DO $$
DECLARE
    day DATE;
BEGIN
    FOR day IN
        SELECT DISTINCT (event_time AT TIME ZONE 'UTC')::date FROM audit_events
    LOOP
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF audit_events_partitioned FOR VALUES FROM (%L) TO (%L)',
            'audit_events_' || to_char(day, 'YYYYMMDD'),
            day::timestamp AT TIME ZONE 'UTC',
            (day + 1)::timestamp AT TIME ZONE 'UTC'
        );
    END LOOP;
END $$;

-- 3. 행을 옮긴다. id를 그대로 복사하므로 identity 시퀀스를 그 뒤로 맞춘다(최근 이벤트 조회가 id 순서를 쓴다).
INSERT INTO audit_events_partitioned
    (id, leaderboard_id, event_id, event_time, event_type, user_id, delta, api_key_id, idempotency_key, created_at)
SELECT id, leaderboard_id, event_id, event_time, event_type, user_id, delta, api_key_id, idempotency_key, created_at
FROM audit_events;

SELECT setval(pg_get_serial_sequence('audit_events_partitioned', 'id'), COALESCE(max(id), 0) + 1, false)
FROM audit_events_partitioned;

-- 4. 이름을 바꾼다.
DROP TABLE audit_events;
ALTER TABLE audit_events_partitioned RENAME TO audit_events;

-- 5. 파티션 테이블의 UNIQUE/PK는 파티션 키를 포함해야 한다(각 파티션의 로컬 인덱스로 강제되기 때문).
--    멱등: event_time은 event_id의 ms 부분에서만 계산되므로(AuditEventConsumer) 같은 이벤트는 항상 같은
--    event_time·같은 파티션으로 간다. (leaderboard_id, event_id)가 같으면 event_time도 같으므로 아래 UNIQUE는
--    V5의 (leaderboard_id, event_id) UNIQUE와 같은 중복을 거부한다.
ALTER TABLE audit_events ADD PRIMARY KEY (id, event_time);
ALTER TABLE audit_events ADD UNIQUE (leaderboard_id, event_id, event_time);

-- 추이 조회: 특정 리더보드의 기간 스캔. event_time 조건으로 파티션을 고른 뒤 각 파티션에서 이 인덱스를 탄다.
CREATE INDEX idx_audit_events_leaderboard_time
    ON audit_events (leaderboard_id, event_time);
